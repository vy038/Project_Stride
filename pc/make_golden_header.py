"""Turn a cfc-cortex-m golden JSON into a small C header the firmware can check itself against.

Usage: python make_golden_header.py golden.json BB out.h  [--seq noise --steps 40]
       (prefix BB for the backbone config, NB for no-backbone)
"""
import argparse, json, os

def cf(v):
    """float -> C float literal. '%.9g' alone turns 1.0 into '1', and '1f' is not valid C."""
    t = f"{float(v):.9g}"
    if not any(c in t for c in ".en"): t += ".0"
    return t + "f"

def c_array(name, values):
    return f"static const float {name}[{len(values)}] = {{ " + ", ".join(cf(v) for v in values) + " };\n"

def write(path, prefix, inputs, ts, outputs, source):
    steps, idim, odim = len(inputs), len(inputs[0]), len(outputs[0])
    with open(path, "w") as f:
        f.write(f"// Generated by tools/make_golden_header.py from {source}. {steps} steps, compared every step.\n#pragma once\n")
        f.write(f"#define GOLDEN_{prefix}_STEPS {steps}\n#define GOLDEN_{prefix}_IN_DIM {idim}\n#define GOLDEN_{prefix}_OUT_DIM {odim}\n")
        f.write(c_array(f"GOLDEN_{prefix}_INPUTS", [v for r in inputs for v in r]))
        f.write(c_array(f"GOLDEN_{prefix}_TS", ts))
        f.write(c_array(f"GOLDEN_{prefix}_OUTPUTS", [v for r in outputs for v in r]))

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("json"); ap.add_argument("prefix", choices=["BB", "NB"]); ap.add_argument("out")
    ap.add_argument("--seq", default="noise"); ap.add_argument("--steps", type=int, default=40)
    a = ap.parse_args()
    d = json.load(open(a.json))
    s = next(x for x in d["sequences"] if x["name"] == a.seq)
    n = a.steps
    ts = s["ts"][:n] if isinstance(s["ts"], list) else [s["ts"]] * n
    write(a.out, a.prefix, s["inputs"][:n], ts, s["outputs"][:n], f"{os.path.basename(a.json)} [{a.seq}]")
