"""Torch-free export of a trained CfC controller into the firmware headers (used by train_cfc_controller.py)."""
import os
from make_golden_header import write as write_golden, c_array, cf

def export(project, W, in_mean, in_std, out_w, out_b, out_mean, out_std, golden_in, golden_out, note):
    """W: dict FF1/FF2/TIME_A/TIME_B -> (weight [hidden x cat] row-major, bias [hidden]) as nested lists/arrays."""
    lib, src = os.path.join(project, "lib", "cfc"), os.path.join(project, "src")
    hidden = len(W["FF1"][1]); in_dim = len(in_mean)
    with open(os.path.join(lib, "weights_nobackbone.h"), "w") as f:
        f.write("/* GENERATED by tools/train_cfc_controller.py: trained CfC joint controller.\n"
                " * Same equations and layout as cfc-cortex-m export_nobackbone.py (ncps 1.0.1 CfCCell,\n"
                " * mode=\"default\", backbone_layers=0). x = concat(input, hx) -> ff1/ff2/time_a/time_b. */\n")
        f.write(f"#define CFC_NB_INPUT_DIM  {in_dim}\n#define CFC_NB_HIDDEN_DIM {hidden}\n")
        f.write("#define CFC_NB_CAT_DIM     (CFC_NB_INPUT_DIM + CFC_NB_HIDDEN_DIM)\n\n")
        for nm in ("FF1", "FF2", "TIME_A", "TIME_B"):
            w, b = W[nm]
            f.write(c_array(f"CFC_NB_{nm}_W", [v for row in w for v in row]))
            f.write(c_array(f"CFC_NB_{nm}_B", list(b)))
    with open(os.path.join(src, "cfc_ctrl_io.h"), "w") as f:
        f.write(f"// GENERATED by tools/train_cfc_controller.py. {note}\n#pragma once\n#define CFC_CTRL_TRAINED 1\n")
        f.write(f"#define CFC_CTRL_IN_DIM  {in_dim}      // err, vel, sin(angle), cos(angle)\n#define CFC_CTRL_HZ      500\n")
        f.write(c_array("CFC_CTRL_IN_MEAN", in_mean).replace(f"[{in_dim}]", "[CFC_CTRL_IN_DIM]"))
        f.write(c_array("CFC_CTRL_IN_STD", in_std).replace(f"[{in_dim}]", "[CFC_CTRL_IN_DIM]"))
        f.write(c_array("CFC_CTRL_OUT_W", out_w))
        f.write(f"static const float CFC_CTRL_OUT_B    = {cf(out_b)};\n")
        f.write(f"static const float CFC_CTRL_OUT_MEAN = {cf(out_mean)};\nstatic const float CFC_CTRL_OUT_STD  = {cf(out_std)};\n")
    write_golden(os.path.join(src, "cfc_golden_nb.h"), "NB", [list(r) for r in golden_in], [1.0] * len(golden_in),
                 [list(r) for r in golden_out], "trained controller, held-out log")
    return lib, src
